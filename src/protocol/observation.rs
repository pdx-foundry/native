#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub(crate) struct ResumeGrant {
    pub version: String,
    pub attempt: String,
    pub game: u32,
    pub worker: u32,
}

pub(crate) fn python_bindings() -> String {
    use crate::protocol::session::ObservationControl;
    let controls = serde_json::json!({
        "normal": ObservationControl::Normal,
        "missing_hook": ObservationControl::MissingHook,
        "late_hook": ObservationControl::LateHook,
        "dropped_record": ObservationControl::DroppedRecord,
        "missing_terminal": ObservationControl::MissingTerminal,
        "access_failure": ObservationControl::AccessFailure,
        "worker_loss": ObservationControl::WorkerLoss,
        "worker_loss_before_activation": ObservationControl::WorkerLossBeforeActivation,
    });
    let schemas = serde_json::json!({
        "request": schemars::schema_for!(WorkerRequest),
        "hello": schemars::schema_for!(WorkerHello),
        "grant": schemars::schema_for!(ResumeGrant),
        "record": schemars::schema_for!(crate::engine::operations::event_stream::WorkerRecord),
        "pause": schemars::schema_for!(PauseWitness),
        "pause_check": schemars::schema_for!(PauseCheck),
        "modifier_table": schemars::schema_for!(ModifierTable),
    });
    format!(
        "# Generated by Native's private protocol authority. Do not edit.\nimport json\nVERSION = {version:?}\nMAX_RECORD = {MAX_RECORD}\nMAX_TRACE = {MAX_TRACE}\nMAX_MODIFIER_TABLE = {MAX_MODIFIER_TABLE}\nCONTROL = json.loads({controls:?})\nSCHEMAS = json.loads({schemas:?})\n{codec}",
        version = VERSION,
        controls = serde_json::to_string(&controls).unwrap(),
        schemas = serde_json::to_string(&schemas).unwrap(),
        codec = include_str!("codec.py"),
    )
}

#[cfg(test)]
mod tests {
    #[test]
    fn generated_python_matches_wire_authority() {
        let generated = super::python_bindings();
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("src/binding/platform/macos/observation/protocol.py");
        if std::env::var_os("PDX_NATIVE_GENERATE_PROTOCOL").is_some() {
            std::fs::write(&path, &generated).unwrap();
        }
        assert_eq!(std::fs::read_to_string(path).unwrap(), generated);
    }
}

